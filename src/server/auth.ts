import { createHash, scrypt, timingSafeEqual } from 'node:crypto';

function scryptAsync(
  password: string,
  salt: string,
  keylen: number,
  options: { N: number; r: number; p: number },
): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    scrypt(password, salt, keylen, options, (err, derivedKey) => {
      if (err) reject(err);
      else resolve(derivedKey);
    });
  });
}

function timingSafeStringEqual(a: string, b: string): boolean {
  const ha = createHash('sha256').update(a).digest();
  const hb = createHash('sha256').update(b).digest();
  return timingSafeEqual(ha, hb);
}

/**
 * Verifies a plaintext password against a `$scrypt$N=...,r=...,p=...$<salt>$<hash>` string
 * generated by `npm run hash-password`.
 */
export async function verifyPasswordHash(
  password: string,
  encodedHash: string,
): Promise<boolean> {
  const parts = encodedHash.trim().split('$');
  // Expected: ['', 'scrypt', 'N=16384,r=8,p=1', '<salt>', '<derived>']
  if (parts.length !== 5 || parts[1] !== 'scrypt') return false;

  const params = Object.fromEntries(
    parts[2].split(',').map((kv) => {
      const [k, v] = kv.split('=');
      return [k, Number.parseInt(v, 10)];
    }),
  );
  const N = params.N;
  const r = params.r;
  const p = params.p;
  if (!Number.isFinite(N) || !Number.isFinite(r) || !Number.isFinite(p)) {
    return false;
  }

  const salt = parts[3];
  const expected = Buffer.from(parts[4], 'base64url');
  if (expected.length === 0) return false;

  const actual = await scryptAsync(password, salt, expected.length, { N, r, p });
  if (actual.length !== expected.length) return false;
  return timingSafeEqual(actual, expected);
}

/**
 * Creates a small cached Basic Auth verifier so browser sub-requests (assets/fonts)
 * don't re-run scrypt on every single image fetch.
 * Always runs scrypt before rejecting an invalid username so timing does not leak valid usernames.
 */
export function createBasicAuthVerifier(expectedUser: string, passwordHash: string) {
  const verifiedCache = new Set<string>();

  return async (authHeader: string | undefined): Promise<boolean> => {
    if (!authHeader || !authHeader.startsWith('Basic ')) return false;
    const cacheKey = createHash('sha256').update(authHeader).digest('hex');
    if (verifiedCache.has(cacheKey)) return true;

    const decoded = Buffer.from(authHeader.slice(6), 'base64').toString('utf8');
    const idx = decoded.indexOf(':');
    const user = idx >= 0 ? decoded.slice(0, idx) : '';
    const pass = idx >= 0 ? decoded.slice(idx + 1) : decoded;

    const userOk = !expectedUser || timingSafeStringEqual(user, expectedUser);
    const passOk = await verifyPasswordHash(pass, passwordHash);
    const ok = userOk && passOk;
    if (ok) {
      if (verifiedCache.size >= 64) verifiedCache.clear();
      verifiedCache.add(cacheKey);
    }
    return ok;
  };
}

interface FailureRecord {
  count: number;
  windowStart: number;
  blockedUntil: number;
}

/**
 * Bounded per-IP rate limiter for failed Basic Auth attempts.
 * Prevents scrypt CPU exhaustion and online password brute-forcing.
 */
export function createAuthRateLimiter(options?: {
  maxFailures?: number;
  windowMs?: number;
  blockMs?: number;
  maxEntries?: number;
}) {
  const maxFailures = options?.maxFailures ?? 10;
  const windowMs = options?.windowMs ?? 15 * 60_000;
  const blockMs = options?.blockMs ?? 15 * 60_000;
  const maxEntries = options?.maxEntries ?? 2048;
  const records = new Map<string, FailureRecord>();

  const prune = (now: number) => {
    if (records.size < maxEntries) return;
    for (const [ip, rec] of records) {
      if (rec.blockedUntil <= now && now - rec.windowStart > windowMs) {
        records.delete(ip);
      }
    }
    if (records.size >= maxEntries) {
      const oldestKey = records.keys().next().value;
      if (oldestKey !== undefined) records.delete(oldestKey);
    }
  };

  return {
    check(ip: string, now = Date.now()): { allowed: boolean; retryAfterSec: number } {
      const rec = records.get(ip);
      if (!rec) return { allowed: true, retryAfterSec: 0 };
      if (rec.blockedUntil > now) {
        return {
          allowed: false,
          retryAfterSec: Math.max(1, Math.ceil((rec.blockedUntil - now) / 1000)),
        };
      }
      if (now - rec.windowStart > windowMs) {
        records.delete(ip);
      }
      return { allowed: true, retryAfterSec: 0 };
    },

    recordFailure(ip: string, now = Date.now()): void {
      prune(now);
      const existing = records.get(ip);
      if (!existing || now - existing.windowStart > windowMs) {
        records.set(ip, {
          count: 1,
          windowStart: now,
          blockedUntil: maxFailures <= 1 ? now + blockMs : 0,
        });
        return;
      }
      existing.count += 1;
      if (existing.count >= maxFailures) {
        existing.blockedUntil = now + blockMs;
      }
    },

    recordSuccess(ip: string): void {
      records.delete(ip);
    },
  };
}
